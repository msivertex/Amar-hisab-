data class LanguagePickerUiCopy(
    val searchPlaceholder: String,
    val primarySectionLabel: String,
    val allLanguagesSectionLabel: String,
    val noMatchingLanguages: String,
    val clearSearchLabel: String,
    val rtlBadgeLabel: String,
    val activeLanguageLabel: String,
    val resultsCountFormat: (Int) -> String
)

object GlobalLanguageStrings {

    private val cache = ConcurrentHashMap<AppLanguage, AppStrings>()

    fun pickerCopy(language: AppLanguage): LanguagePickerUiCopy {
        if (language.isBangla) {
            return LanguagePickerUiCopy(
                searchPlaceholder = "ভাষা, লিপি বা অঞ্চল খুঁজুন (যেমন: বাংলা, हिन्दी, العربية)...",
                primarySectionLabel = "জনপ্রিয় ও প্রস্তাবিত ভাষা",
                allLanguagesSectionLabel = "সকল ভাষা",
                noMatchingLanguages = "এই নামে কোনো ভাষা পাওয়া যায়নি",
                clearSearchLabel = "সার্চ মুছুন",
                rtlBadgeLabel = "RTL",
                activeLanguageLabel = "নির্বাচিত",
                resultsCountFormat = { count -> "${BdtFormatter.formatNumber(count, language)}টি ভাষা" }
            )
        }
        val overlay = overlays[language]
        return LanguagePickerUiCopy(
            searchPlaceholder = overlay?.searchPlaceholder
                ?: "Search language, native script, or region...",
            primarySectionLabel = overlay?.primarySectionLabel ?: "Suggested / Popular Languages",
            allLanguagesSectionLabel = overlay?.allLanguagesSectionLabel ?: "All Languages",
            noMatchingLanguages = overlay?.noMatchingLanguages ?: "No languages match your search",
            clearSearchLabel = overlay?.cancel ?: "Clear",
            rtlBadgeLabel = "RTL",
            activeLanguageLabel = overlay?.activeBadge ?: "Active",
            resultsCountFormat = { count -> "$count languages" }
        )
    }

    fun forLanguage(language: AppLanguage, baseEnglish: AppStrings): AppStrings {
        if (language == AppLanguage.EN) return baseEnglish
        return cache.getOrPut(language) {
            val ov = overlays[language]
            val reportCopy = ReportLocalizedStrings.forLanguage(language)
            val localizedExport = baseEnglish.reportExport.copy(
                cardTitle = reportCopy.monthlyReportTitle,
                cardSubtitle = "${reportCopy.dailyTab} • ${reportCopy.weeklyTab} • ${reportCopy.monthlyTab} (PDF / CSV / QR)",
                sheetTitle = reportCopy.monthlyReportTitle,
                sheetSubtitle = "${reportCopy.brandTitle} • ${language.nativeName}",
                transactionsCountSuffix = reportCopy.txCountSuffix,
                periodBadgePrefix = reportCopy.periodLabel,
                shareSubjectPrefix = reportCopy.shareTitlePrefix
            )
            if (ov == null) {
                return@getOrPut baseEnglish.copy(
                    netFlowLabel = reportCopy.netFlowLabel,
                    dailyAverageLabel = reportCopy.dailyAverageLabel,
                    spendingByCategory = reportCopy.categoryBreakdownTitle,
                    reportExport = localizedExport
                )
            }
            baseEnglish.copy(
                navHome = ov.navHome,
                navActivity = ov.navActivity,
                navPlan = ov.navPlan,
                navInsights = ov.navInsights,
                totalBalance = ov.totalBalance,
                spentThisMonth = ov.spentThisMonth,
                dailyAverageLabel = reportCopy.dailyAverageLabel,
                myWallets = ov.myWallets,
                allAccounts = ov.accountsTitle,
                monthlyBudget = ov.planTabBudgets,
                recentTransactions = ov.recentTransactions,
                seeAll = ov.seeAll,
                accountsTitle = ov.accountsTitle,
                addAccount = ov.addAccount,
                addTransactionTitle = ov.saveTransaction,
                expenseLabel = ov.expenseLabel,
                incomeLabel = ov.incomeLabel,
                transferLabel = ov.transferLabel,
                actionExpense = ov.expenseLabel,
                actionTransfer = ov.transferLabel,
                saveTransaction = ov.saveTransaction,
                activityTitle = ov.activityTitle,
                planTitle = ov.planTitle,
                planTabBudgets = ov.planTabBudgets,
                planTabGoals = ov.planTabGoals,
                planTabLoans = ov.planTabLoans,
                savingsGoals = ov.planTabGoals,
                loansTitle = ov.planTabLoans,
                insightsTitle = ov.insightsTitle,
                netFlowLabel = reportCopy.netFlowLabel,
                spendingByCategory = reportCopy.categoryBreakdownTitle,
                settingsTitle = ov.settingsTitle,
                settingsCustomization = ov.settingsCustomization,
                languageLabel = ov.languageLabel,
                customizeDashboard = ov.customizeDashboard,
                saveChanges = ov.saveChanges,
                cancel = ov.cancel,
                close = ov.close,
                reportExport = localizedExport,
                themeSettings = baseEnglish.themeSettings.copy(
                    themeTileTitle = ov.themeTitle,
                    activeThemeBadge = ov.activeBadge
                ),
                settingsRefinement = baseEnglish.settingsRefinement.copy(
                    languageTileTitle = ov.languageLabel,
                    languagePageTitle = ov.languagePageTitle,
                    languagePageSubtitle = ov.languagePageSubtitle,
                    languageInstantNote = ov.languageInstantNote
                )
            )
        }
    }

