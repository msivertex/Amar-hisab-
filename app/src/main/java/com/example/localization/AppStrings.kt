object BdtFormatter {
    private val banglaDigits = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')

    fun format(amount: Double, language: AppLanguage, includeSign: Boolean = false): String =
        formatCurrency(amount, AppCurrency.BDT.code, language, includeSign)

    fun formatCurrency(
        amount: Double,
        currencyCode: String,
        language: AppLanguage,
        includeSign: Boolean = false
    ): String {
        val currency = AppCurrency.fromCode(currencyCode)
        val sign = when {
            amount < 0 -> "-"
            includeSign && amount > 0 -> "+"
            else -> ""
        }
        val numeric = formatAmountOnly(abs(amount), currencyCode, language, includeSign = false)
        return "${sign}${currency.code} $numeric"
    }

    fun formatBalance(
        amount: Double,
        currencyCode: String,
        language: AppLanguage
    ): String {
        val safeAmount = if (!amount.isFinite() || amount <= 0.0005) 0.0 else amount
        return formatCurrency(safeAmount, currencyCode, language, includeSign = false)
    }

    /**
     * Formats the numeric portion without repeating the ISO code (for balance rows
     * where the ISO code is rendered inside a uniform leading badge pill, e.g., "[KWD] 244.000").
     */
    fun formatSymbolAndAmount(
        amount: Double,
        currencyCode: String,
        language: AppLanguage,
        includeSign: Boolean = false
    ): String {
        val sign = when {
            amount < 0 -> "-"
            includeSign && amount > 0 -> "+"
            else -> ""
        }
        val numeric = formatAmountOnly(abs(amount), currencyCode, language, includeSign = false)
        return "${sign}$numeric"
    }

    fun formatSymbolAndBalance(
        amount: Double,
        currencyCode: String,
        language: AppLanguage
    ): String {
        val safeAmount = if (!amount.isFinite() || amount <= 0.0005) 0.0 else amount
        return formatSymbolAndAmount(safeAmount, currencyCode, language, includeSign = false)
    }

    fun formatAmountOnly(
        amount: Double,
        currencyCode: String,
        language: AppLanguage,
        includeSign: Boolean = false
    ): String {
        val currency = AppCurrency.fromCode(currencyCode)
        val isNegative = amount < 0
        val absVal = abs(amount)
        val forceFixedThreeDecimals = currency.code.equals("KWD", ignoreCase = true)
        val hasFractional = forceFixedThreeDecimals ||
            (currency.decimalPlaces > 0 && abs(absVal - absVal.roundToLong()) >= 0.0005)
        val raw = if (hasFractional) {
            val decimals = when {
                forceFixedThreeDecimals -> 3
                currency.decimalPlaces == 3 -> 3
                else -> 2
            }
            val formattedUs = String.format(Locale.US, "%.${decimals}f", absVal)
            val dotIdx = formattedUs.indexOf('.')
            val wholeLong = formattedUs.substring(0, dotIdx).toLongOrNull() ?: absVal.toLong()
            val wholeFormatted = if (currency.usesIndianGrouping) {
                formatIndianGrouping(wholeLong)
            } else {
                formatInternationalGrouping(wholeLong)
            }
            val fracPart = formattedUs.substring(dotIdx + 1)
            "$wholeFormatted.$fracPart"
        } else {
            val rounded = absVal.roundToLong()
            if (currency.usesIndianGrouping) formatIndianGrouping(rounded) else formatInternationalGrouping(rounded)
        }
        val localized = if (language.isBangla) toBanglaDigits(raw) else raw
        val sign = when {
            isNegative -> "-"
            includeSign && amount > 0 -> "+"
            else -> ""
        }
        return "$sign$localized"
    }

    private fun formatInternationalGrouping(number: Long): String {
        val s = number.toString()
        if (s.length <= 3) return s
        val sb = StringBuilder()
        var count = 0
        for (i in s.lastIndex downTo 0) {
            if (count > 0 && count % 3 == 0) sb.append(',')
            sb.append(s[i])
            count++
        }
        return sb.reverse().toString()
    }

    fun formatNumber(value: Int, language: AppLanguage): String {
        val s = value.toString()
        return if (language.isBangla) toBanglaDigits(s) else s
    }

    fun formatPercent(value: Int, language: AppLanguage): String {
        val s = "${value.coerceIn(0, 999)}%"
        return if (language.isBangla) toBanglaDigits(s) else s
    }

    fun toBanglaDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            if (ch in '0'..'9') {
                sb.append(banglaDigits[ch - '0'])
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    private fun formatIndianGrouping(number: Long): String {
        val s = number.toString()
        if (s.length <= 3) return s
        val lastThree = s.substring(s.length - 3)
        var rest = s.substring(0, s.length - 3)
        val groups = mutableListOf<String>()
        while (rest.length > 2) {
            groups.add(0, rest.substring(rest.length - 2))
            rest = rest.substring(0, rest.length - 2)
        }
        if (rest.isNotEmpty()) {
            groups.add(0, rest)
        }
        return groups.joinToString(",") + "," + lastThree
    }
}

