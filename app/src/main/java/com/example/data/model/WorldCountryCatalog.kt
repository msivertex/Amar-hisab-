    internal val defaultPerUsdMap: Map<String, Double> by lazy {
        currencySpecs.associate { it.code to it.defaultPerUsd }
    }

    fun defaultPerUsd(currencyCode: String): Double {
        val normalized = currencyCode.trim().uppercase(Locale.ROOT)
        return defaultPerUsdMap[normalized] ?: 1.0
    }

    fun isKnownCurrencyCode(currencyCode: String?): Boolean {
        if (currencyCode.isNullOrBlank()) return false
        return defaultPerUsdMap.containsKey(currencyCode.trim().uppercase(Locale.ROOT))
    }

