/**
 * Supported receipt / report generation periods.
 */
enum class ReportPeriodType {
    DAILY,
    WEEKLY,
    MONTHLY
}

/**
 * Complete language-aware copy for Daily, Weekly, and Monthly PDF/CSV receipts and verification QR codes.
 */
data class ReportLocalizedCopy(
    val brandTitle: String,
    val dailyTab: String,
    val weeklyTab: String,
    val monthlyTab: String,
    val dailyReportTitle: String,
    val weeklyReportTitle: String,
    val monthlyReportTitle: String,
    val periodLabel: String,
    val accountHolderLabel: String,
    val generatedLabel: String,
    val totalIncomeLabel: String,
    val totalExpenseLabel: String,
    val netFlowLabel: String,
    val dailyAverageLabel: String,
    val budgetUsedLabel: String,
    val savingsRateLabel: String,
    val perCurrencyTitle: String,
    val categoryBreakdownTitle: String,
    val transactionsLedgerTitle: String,
    val colDate: String,
    val colTitleCategory: String,
    val colWallet: String,
    val colAmount: String,
    val noExpenseMessage: String,
    val noTransactionsMessage: String,
    val qrSectionTitle: String,
    val qrScanCaption: String,
    val qrVerifyCodeLabel: String,
    val qrShareOptionTitle: String,
    val qrShareOptionSubtitle: String,
    val voucherQrTitle: String,
    val voucherQrSubtitle: String,
    val txCountSuffix: String,
    val transferShortLabel: String,
    val footerText: String,
    val shareTitlePrefix: String
) {
    fun periodTabLabel(type: ReportPeriodType): String = when (type) {
        ReportPeriodType.DAILY -> dailyTab
        ReportPeriodType.WEEKLY -> weeklyTab
        ReportPeriodType.MONTHLY -> monthlyTab
    }

    fun reportTitleFor(type: ReportPeriodType): String = when (type) {
        ReportPeriodType.DAILY -> dailyReportTitle
        ReportPeriodType.WEEKLY -> weeklyReportTitle
        ReportPeriodType.MONTHLY -> monthlyReportTitle
    }
}

